// ---------- core t() ----------
function t(s) {
  if (!s || typeof s !== 'string' || _lang !== 'zh') return s;
  const d = ZH[s];
  if (d) return d;
  // fall back to a trimmed-key lookup so split banner sentences
  // (e.g. text following an inline <b>) still hit the dictionary,
  // while preserving the original leading/trailing whitespace
  const trimmed = s.trim();
  if (trimmed !== s && ZH[trimmed]) {
    return s.match(/^\s*/)[0] + ZH[trimmed] + s.match(/\s*$/)[0];
  }
  // R95: multi-line JSX text — collapse internal whitespace (newlines /
  // double spaces) so line-broken paragraphs still hit the dictionary
  const flat = trimmed !== s || /\s{2,}|\n/.test(s) ? trimmed.replace(/\s+/g, ' ') : s;
  if (flat !== s) {
    if (ZH[flat]) return ZH[flat];
    for (let i = 0; i < PATTERNS.length; i++) {
      const m = flat.match(PATTERNS[i][0]);
      if (m) return PATTERNS[i][1].replace(/\$(\d+)/g, (_, n) => ifnull(m[Number(n)], ''));
    }
  }
  for (let i = 0; i < PATTERNS.length; i++) {
    const m = s.match(PATTERNS[i][0]);
    if (m) return PATTERNS[i][1].replace(/\$(\d+)/g, (_, n) => ifnull(m[Number(n)], ''));
  }
  return s;
}

function setLang(l) {
  _lang = l;
  try { if (typeof localStorage !== 'undefined') localStorage.setItem('lang', l); } catch (e) { /* noop */ }
}
function getLang() { return _lang; }

// ---------- React.createElement patch ----------
(function patch() {
  if (!window.React || !React.createElement) return;
  const orig = React.createElement;
  const TRANS_PROPS = ['label','title','placeholder','confirmText','message','empty','emptyHint','hint','aria-label','activeText','inactiveText'];


  React.createElement = function(type, props, ...children) {
    if (props) {
      let dirty = false;
      const newProps = { ...props };
      for (const k of TRANS_PROPS) {
        if (typeof props[k] === 'string') { newProps[k] = t(props[k]); dirty = true; }
      }
      return orig.call(React, type, dirty ? newProps : props, ...children.map(c => (typeof c === 'string' ? t(c) : c)));
    }
    return orig.call(React, type, props, ...children.map(c => (typeof c === 'string' ? t(c) : c)));
  };
})();

